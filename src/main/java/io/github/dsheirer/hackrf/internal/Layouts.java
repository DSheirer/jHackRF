package io.github.dsheirer.hackrf.internal;

import static java.lang.foreign.MemoryLayout.PathElement.groupElement;
import static java.lang.foreign.MemoryLayout.paddingLayout;
import static java.lang.foreign.MemoryLayout.sequenceLayout;
import static java.lang.foreign.MemoryLayout.structLayout;
import static java.lang.foreign.ValueLayout.ADDRESS;
import static java.lang.foreign.ValueLayout.JAVA_BYTE;
import static java.lang.foreign.ValueLayout.JAVA_INT;
import static java.lang.foreign.ValueLayout.JAVA_SHORT;

import java.lang.foreign.GroupLayout;
import java.lang.foreign.MemoryLayout;
import java.lang.foreign.MemorySegment;

/**
 * Memory layouts of the structures in {@code hackrf.h}.
 *
 * <p>These are written by hand rather than generated by jextract. Apart from
 * pointers, every field has a fixed width, and every supported platform is
 * 64-bit, so a single set of layouts is correct on all of them.
 */
public final class Layouts {
    /** Bytes in each block of samples, {@code BYTES_PER_BLOCK}. */
    public static final int BYTES_PER_BLOCK = 16384;

    /** Most frequency ranges a sweep accepts, {@code MAX_SWEEP_RANGES}. */
    public static final int MAX_SWEEP_RANGES = 10;

    /** {@code HACKRF_OPERACAKE_ADDRESS_INVALID}: an unused entry in the board list. */
    public static final int OPERACAKE_ADDRESS_INVALID = 0xFF;

    /** {@code HACKRF_OPERACAKE_MAX_BOARDS}. */
    public static final int OPERACAKE_MAX_BOARDS = 8;

    /** {@code HACKRF_OPERACAKE_MAX_DWELL_TIMES}. */
    public static final int OPERACAKE_MAX_DWELL_TIMES = 16;

    /** {@code HACKRF_OPERACAKE_MAX_FREQ_RANGES}. */
    public static final int OPERACAKE_MAX_FREQ_RANGES = 8;

    /** {@code hackrf_transfer}. */
    public static final GroupLayout TRANSFER = structLayout(
        ADDRESS.withName("device"),
        ADDRESS.withName("buffer"),
        JAVA_INT.withName("buffer_length"),
        JAVA_INT.withName("valid_length"),
        ADDRESS.withName("rx_ctx"),
        ADDRESS.withName("tx_ctx"));

    /** {@code read_partid_serialno_t}. */
    public static final GroupLayout PART_SERIAL = structLayout(
        sequenceLayout(2, JAVA_INT).withName("part_id"),
        sequenceLayout(4, JAVA_INT).withName("serial_no"));

    /** {@code hackrf_operacake_dwell_time}. */
    public static final GroupLayout OPERACAKE_DWELL_TIME = structLayout(
        JAVA_INT.withName("dwell"),
        JAVA_BYTE.withName("port"),
        paddingLayout(3));

    /** {@code hackrf_operacake_freq_range}. */
    public static final GroupLayout OPERACAKE_FREQ_RANGE = structLayout(
        JAVA_SHORT.withName("freq_min"),
        JAVA_SHORT.withName("freq_max"),
        JAVA_BYTE.withName("port"),
        paddingLayout(1));

    /** {@code hackrf_bool_user_settting}; {@code bool} is one byte. */
    public static final GroupLayout BOOL_USER_SETTING = structLayout(
        JAVA_BYTE.withName("do_update"),
        JAVA_BYTE.withName("change_on_mode_entry"),
        JAVA_BYTE.withName("enabled"));

    /** {@code hackrf_bias_t_user_settting_req}. */
    public static final GroupLayout BIAS_T_USER_SETTING_REQ = structLayout(
        BOOL_USER_SETTING.withName("tx"),
        BOOL_USER_SETTING.withName("rx"),
        BOOL_USER_SETTING.withName("off"));

    /** {@code hackrf_m0_state}. */
    public static final GroupLayout M0_STATE = structLayout(
        JAVA_SHORT.withName("requested_mode"),
        JAVA_SHORT.withName("request_flag"),
        JAVA_INT.withName("active_mode"),
        JAVA_INT.withName("m0_count"),
        JAVA_INT.withName("m4_count"),
        JAVA_INT.withName("num_shortfalls"),
        JAVA_INT.withName("longest_shortfall"),
        JAVA_INT.withName("shortfall_limit"),
        JAVA_INT.withName("threshold"),
        JAVA_INT.withName("next_mode"),
        JAVA_INT.withName("error"));

    /** {@code hackrf_selftest}. */
    public static final GroupLayout SELFTEST = structLayout(
        JAVA_BYTE.withName("pass"),
        sequenceLayout(4095, JAVA_BYTE).withName("msg"));

    /** {@code struct hackrf_device_list}. */
    public static final GroupLayout DEVICE_LIST = structLayout(
        ADDRESS.withName("serial_numbers"),
        ADDRESS.withName("usb_board_ids"),
        ADDRESS.withName("usb_device_index"),
        JAVA_INT.withName("devicecount"),
        paddingLayout(ADDRESS.byteSize() - JAVA_INT.byteSize()),
        ADDRESS.withName("usb_devices"),
        JAVA_INT.withName("usb_devicecount"),
        paddingLayout(ADDRESS.byteSize() - JAVA_INT.byteSize()));

    private Layouts() {
    }

    /** Returns the byte offset of a named field of a structure. */
    public static long offset(MemoryLayout layout, String field) {
        return layout.byteOffset(groupElement(field));
    }

    /** Returns the byte offset of a field of a nested structure. */
    public static long offset(MemoryLayout layout, String field, String nested) {
        return layout.byteOffset(groupElement(field), groupElement(nested));
    }

    /** Reads an unsigned 32-bit field. */
    public static long u32(MemorySegment segment, MemoryLayout layout, String field) {
        return Integer.toUnsignedLong(segment.get(JAVA_INT, offset(layout, field)));
    }

    /** Reads an unsigned 16-bit field. */
    public static int u16(MemorySegment segment, MemoryLayout layout, String field) {
        return Short.toUnsignedInt(segment.get(JAVA_SHORT, offset(layout, field)));
    }
}
